# Unit-2D_Task-1_String_Creation_Basic_Operations.py
str1 = "Hello"
str2 = "World"

# Concatenation
result_concat = str1 + " " + str2
print("Concatenation:", result_concat)

# Repetition
result_repeat = str1 * 3
print("Repetition:", result_repeat)

# Slicing
text = "PythonProgramming"
print("First 6 characters:", text[:6])
print("Characters from index 6 onwards:", text[6:])
print("Reversed using slicing:", text[::-1])