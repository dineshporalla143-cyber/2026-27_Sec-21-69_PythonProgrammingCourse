# Create a list
mylist = [10, 30, 20, 50]

# Append
mylist.append(60)
print("After append:", mylist)

# Insert
mylist.insert(1, 15)
print("After insert:", mylist)

# Remove
mylist.remove(30)
print("After remove:", mylist)

# Sort
mylist.sort()
print("After sort:", mylist)

# Reverse
mylist.reverse()
print("After reverse:", mylist)